// ราหูกาล: แบ่งกลางวัน (ประมาณ 06:00-18:00) เป็น 8 ช่วง ช่วงละ 1.5 ชม. ลำดับตามวันในสัปดาห์ (อาทิตย์=0)
const RAHU_SLOT = [8, 2, 7, 5, 6, 4, 3];
const hhmm = (min) => `${String(Math.floor(min / 60)).padStart(2, "0")}:${String(min % 60).padStart(2, "0")}`;
export function rahuKalam(weekday) {
  const start = 360 + (RAHU_SLOT[weekday] - 1) * 90;
  return `${hhmm(start)}-${hhmm(start + 90)}`;
}
// อภิชิตมุหูรตะ: ช่วงกลางวันพอดี (ราว 11:36-12:24) ตำราว่าดีสำหรับเริ่มงาน ยกเว้นวันพุธ
export const abhijit = (weekday) => (weekday === 3 ? null : "11:36-12:24");

const TARA_TONE = { "ดีมาก": 1, "ดี": 0.5, "กลาง": 0, "ระวัง": -0.5 };
const half = (x) => Math.max(1, Math.min(5, Math.round(x * 2) / 2));
const level = (s) => (s >= 4 ? "high" : s >= 3 ? "mid" : "low");

// natal: { nakIndex, rashi, m, d } ของคนดู · y, m, d: วันที่ต้องการดู (เวลาไทย)
export function dailyReading(natal, y, m, d) {
  const moon = nakshatraAt(thaiDate(y, m, d, 6, 0));
  const taraNo = taraOf(natal.nakIndex, moon.index);
  const tara = TARAS[taraNo];
  const house = ((moon.rashi - natal.rashi + 12) % 12) + 1;
  const ch = CHANDRA[house];
  const weekday = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
  const seed = y * 372 + m * 31 + d;

  const base = 3 + (TARA_TONE[tara.tone] ?? 0) + ch.tone * 0.5;
  const areas = DAY_AREAS.map((a, i) => {
    let s = base;
    if (ch.focus === a.key) s += ch.tone >= 0 ? 0.5 + ch.tone * 0.5 : ch.tone * 0.5;
    if (tara.theme === a.theme) s += (TARA_TONE[tara.tone] ?? 0) >= 0 ? 0.5 : -0.5;
    const score = half(s);
    const lv = level(score);
    return { ...a, score, text: AREA_TEXT[a.key][lv][(seed + i) % 2] };
  });

  const personalYear = reduce(natal.m + natal.d + y, false);
  const dayNumber = reduce(personalYear + m + d, false);

  return {
    moon, taraNo, tara, house, chandra: ch, weekday,
    overall: half(areas.reduce((t, a) => t + a.score, 0) / areas.length),
    areas,
    color: THAI_DAYS[weekday],
    rahu: rahuKalam(weekday),
    good: abhijit(weekday),
    dayNumber, dayTip: DAY_NUMBER_TIP[dayNumber],
  };
}
