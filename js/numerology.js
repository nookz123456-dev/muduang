const TH_VALUES = {
  1: "กดถทภฤาำุ่",
  2: "ขชงบปเแู้",
  3: "ฆตฑฒ๋",
  4: "คธญษโะัิ",
  5: "ฉฌณนมหฎฮฬึ",
  6: "จลวอใ",
  7: "ซศสืี็๊",
  8: "ยผฝพฟไ",
  9: "ฏฐ์",
};
const MAP = {};
for (const [v, chars] of Object.entries(TH_VALUES)) for (const c of chars) MAP[c] = Number(v);

const digitsSum = (n) => String(n).split("").reduce((s, d) => s + Number(d), 0);
export function reduce(n, keepMaster = true) {
  while (n > 9 && !(keepMaster && (n === 11 || n === 22 || n === 33))) n = digitsSum(n);
  return n;
}

export function lifePath(y, m, d) {
  return reduce(digitsSum(y) + digitsSum(m) + digitsSum(d));
}

export function nameNumber(name) {
  const chars = [...name].filter((c) => MAP[c]);
  const total = chars.reduce((s, c) => s + MAP[c], 0);
  return { total, root: total ? reduce(total, false) : 0, counted: chars.length };
}

