export const THREE_WONDERS = [1, 2, 3]; // 乙丙丁 บนจานฟ้า = สามอัศจรรย์ (三奇)

export function palaceScore(pl) {
  if (!pl.door) return null;
  let s = DOOR_INFO[pl.door].score + starInfo(pl.star).score + DEITY_INFO[pl.deity].score;
  if (pl.heaven.some((x) => THREE_WONDERS.includes(x))) s += 1;
  return s;
}
