// สุ่มด้วย crypto (ยุติธรรมกว่า Math.random)
function randInt(n) {
  const a = new Uint32Array(1);
  crypto.getRandomValues(a);
  return a[0] % n;
}

export function drawCards(n) {
  const deck = CARDS.map((_, i) => i);
  for (let i = deck.length - 1; i > 0; i--) {
    const j = randInt(i + 1);
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck.slice(0, n).map((i) => ({ card: CARDS[i], reversed: randInt(2) === 1 }));
}

// ไพ่ประจำวัน: วันเดียวกันได้ใบเดิม (seed จากวันที่ + ฤกษ์เกิด)
export function dailyCard(dayKey, birthIndex, hash) {
  const h = hash(`tarot:${dayKey}:${birthIndex}`);
  return { card: CARDS[h % CARDS.length], reversed: (h >>> 8) % 4 === 0 }; // กลับหัว 1 ใน 4 ให้ไพ่ประจำวันไม่หนักเกินไป
}
